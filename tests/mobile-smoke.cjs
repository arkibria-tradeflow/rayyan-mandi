const {chromium}=require("playwright");
const assert=require("node:assert/strict");
(async()=>{
 const browser=await chromium.launch({headless:true,args:["--no-sandbox"]});
 const page=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
 const errors=[];page.on("pageerror",e=>errors.push(e.message));
 const base="http://127.0.0.1:8765/";
 await page.goto(base+"official-menu.html",{waitUntil:"networkidle"});
 await page.waitForSelector(".card",{timeout:12000});
 assert.equal(await page.locator(".card").count(),71);
 assert.ok((await page.locator("#catalog").innerText()).includes("Chicken Mandi"));
 assert.ok((await page.locator("#catalog").innerText()).includes("AED 29"));
 assert.ok((await page.locator("#catalog").innerText()).includes("Haneeth Shoulder"));
 assert.ok((await page.locator("#catalog").innerText()).includes("AED 89"));
 assert.ok((await page.locator("#catalog").innerText()).includes("Market price"));
 console.log("PASS official 71 dishes and confirmed menu pricing");
 const img=page.locator('.card img[src="assets/menu/fish-grilled.webp"]').first();
 assert.ok(await img.count()>0);
 assert.ok(await img.evaluate(async el=>{el.loading="eager";if(!el.complete)await new Promise(r=>{el.addEventListener("load",r,{once:true});el.addEventListener("error",r,{once:true});setTimeout(r,5000)});return el.naturalWidth>0}));
 console.log("PASS existing local menu photos");
 await page.locator("#search").fill("Chicken Mandi");
 assert.equal(await page.locator(".card").count(),1);
 await page.locator(".add").click();
 await page.locator("#order").click();
 await page.waitForURL(/order\.html/);
 assert.ok((await page.locator("#items").innerText()).includes("Chicken Mandi"));
 console.log("PASS searchable ordering and basket transfer");
 await page.goto(base+"official-menu.html");
 await page.locator("#lang").click();
 assert.equal(await page.locator("html").getAttribute("dir"),"rtl");
 console.log("PASS Arabic RTL");
 await page.goto(base+"menu.html");
 await page.waitForURL(/official-menu\.html/);
 console.log("PASS old URL redirect");
 assert.deepEqual(errors,[]);
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
