const {chromium}=require("playwright");
const assert=require("node:assert/strict");
(async()=>{
 const browser=await chromium.launch({headless:true,args:["--no-sandbox"]});
 const page=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
 const errors=[];
 page.on("pageerror",e=>errors.push(e.message));
 const base="http://127.0.0.1:8765/";
 await page.goto(base+"menu.html",{waitUntil:"domcontentloaded"});
 await page.waitForSelector(".rayyan-menu-card",{timeout:15000});
 console.log("Menu cards",await page.locator(".rayyan-menu-card").count());
 assert.equal(await page.locator(".rayyan-menu-card").count(),32);
 assert.ok(await page.locator(".rayyan-menu-illustration.photo img").count()>15,"Food photos not injected");
 const photoIds=["extra12","extra13","extra16","extra17","extra18","extra19","extra20","extra21","extra22","extra23"];
 for(const id of photoIds){
   const img=page.locator('.rayyan-menu-card[data-id="'+id+'"] img');
   assert.equal(await img.count(),1,id+" should have real photo");
   const url=await img.getAttribute("src");
   assert.ok(url && url.endsWith(".webp"),id+" should use local WebP");
   const loaded=await img.evaluate(async el=>{
     el.loading="eager";
     if(!el.complete) await new Promise(resolve=>{el.addEventListener("load",resolve,{once:true});el.addEventListener("error",resolve,{once:true});setTimeout(resolve,7000)});
     return el.complete && el.naturalWidth>0;
   });
   assert.ok(loaded,id+" photo failed to load");
 }
 console.log("PASS: ten previously missing dish images render and load");
 assert.ok((await page.locator("#verifiedBranchPanel").innerText()).includes("11:00"),"Verified branch hours missing");
 await page.locator('[data-add="extra5"]').click();
 assert.ok(Number(await page.locator("#cartCount").innerText())>=1,"Basket count did not increment");
 await page.locator("#navOrder").click();
 await page.waitForSelector("#cartOverlay.open");
 await page.locator("#sendWhatsApp").click();
 await page.waitForURL(/order\.html/,{timeout:15000});
 assert.ok((await page.locator("#items").innerText()).includes("Chicken Mandi"),"Basket not transferred");
 await page.locator("#name").fill("Demo Guest");
 await page.locator("#phone").fill("+971501234567");
 await page.locator('[data-mode="delivery"]').click();
 await page.locator("#address").fill("Sample Building, Dubai, UAE");
 await page.locator("#review").click();
 await page.waitForSelector("#modal.open");
 const text=await page.locator("#preview").innerText();
 assert.ok(text.includes("DEMO WEBSITE INQUIRY")&&text.includes("Chicken Mandi")&&text.includes("Sample Building"));
 console.log("PASS: menu selection → basket → checkout → WhatsApp review");
 await page.goto(base+"branches.html");
 assert.equal(await page.locator(".branch").count(),6);
 await page.locator('[data-country="qatar"]').click();
 assert.equal(await page.locator(".branch").count(),1);
 assert.ok((await page.locator(".branch").innerText()).includes("Al Wukair"));
 await page.locator(".choose").click();
 await page.waitForURL(/menu\.html/);
 assert.ok((await page.locator("#verifiedBranchPanel").innerText()).includes("Al Wukair"));
 console.log("PASS: six branches, Qatar location, branch selection persistence");
 await page.locator("#langBtn").click();
 assert.equal(await page.locator("html").getAttribute("dir"),"rtl");
 console.log("PASS: Arabic direction");
 await page.goto(base+"index.html");
 assert.ok(await page.locator("#verifiedBranchPanel").count()>0);
 console.log("PASS: homepage branch card");
 assert.deepEqual(errors,[],"JavaScript errors: "+errors.join("; "));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
